struct ExamDesk {
    var calendar: Calendar

    static let examYear = 2026
    static let examMonth = 12
    static let examDay = 19

    struct Snapshot: Equatable {
        var daysRemaining: Int
        var showsNumber: Bool
        var headline: String
        var dateLine: String
        var note: String
        var accessibilityLabel: String
    }

    func daysRemaining(on date: Date) -> Int {
        let today = calendar.startOfDay(for: date)
        let exam = calendar.date(from: DateComponents(year: Self.examYear, month: Self.examMonth, day: Self.examDay, hour: 12))!
        return calendar.dateComponents([.day], from: today, to: calendar.startOfDay(for: exam)).day ?? 0
    }

    func note(daysRemaining: Int) -> String {
        if daysRemaining > 51 { return Self.earlyNote }
        if daysRemaining < 0 { return Self.afterNote }
        return Self.notes[daysRemaining] ?? Self.earlyNote
    }

    func snapshot(on date: Date) -> Snapshot {
        let days = daysRemaining(on: date)
        let written = note(daysRemaining: days)
        if days > 0 {
            return Snapshot(
                daysRemaining: days, showsNumber: true,
                headline: "还有 \(days) 天", dateLine: "12月19日 初试", note: written,
                accessibilityLabel: "距离初试还有 \(days) 天，12月19日"
            )
        }
        if days == 0 {
            return Snapshot(
                daysRemaining: 0, showsNumber: false,
                headline: "初试这一天", dateLine: "12月19日 初试", note: written,
                accessibilityLabel: "初试这一天，12月19日"
            )
        }
        return Snapshot(
            daysRemaining: days, showsNumber: false,
            headline: "", dateLine: "", note: written, accessibilityLabel: written
        )
    }

    static func referenceNow(calendar: Calendar = .current) -> Date {
        #if DEBUG
        let arguments = ProcessInfo.processInfo.arguments
        if let index = arguments.firstIndex(of: "-ui-test-today"), arguments.indices.contains(index + 1) {
            let parts = arguments[index + 1].split(separator: "-").compactMap { Int($0) }
            if parts.count == 3, let date = calendar.date(from: DateComponents(year: parts[0], month: parts[1], day: parts[2], hour: 12)) {
                return date
            }
        }
        #endif
        return Date()
    }

